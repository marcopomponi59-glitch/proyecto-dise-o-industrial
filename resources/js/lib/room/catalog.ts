import type { TextureUse } from './textures';
import type { Mount, Shape } from './types';

export interface CatalogEntry {
    type: string;
    name: string;
    category: CatalogCategory;
    /** Forma simple: se usa mientras carga el modelo, o siempre si no tiene modelo. */
    shape: Shape;
    mount: Mount;
    width: number;
    depth: number;
    height: number;
    /** Altura sugerida desde el piso (para lo que va colgado o apoyado sobre otro mueble). */
    elevation: number;
    color: string;
    /** Modelo 3D en `public/models/kenney/{model}.glb` (Kenney Furniture Kit, CC0). */
    model?: string;
    /** Giro en grados para que el frente del modelo quede mirando hacia +Z. */
    modelRotation?: number;
    /** Materiales del modelo que toman el color del objeto (tela, madera…). Sin esto el color no se puede cambiar. */
    tint?: string[];
    /** Da luz en la vista 3D y se puede prender y apagar. */
    light?: boolean;
    /** Acepta un tema o una foto: como imagen única (cuadros) o como estampado (camas, alfombras). */
    textured?: TextureUse;
}

